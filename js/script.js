const languageSelect = document.getElementById('languageSelect');
const supportedLanguages = Object.keys(translations);
const savedLanguage = localStorage.getItem('language');
let currentLanguage = supportedLanguages.includes(savedLanguage) ? savedLanguage : 'de';

const translatePage = (language) => {
	currentLanguage = language;
	document.documentElement.lang = language;
	document.querySelectorAll('[data-i18n]').forEach((element) => {
		element.textContent = translations[language][element.dataset.i18n];
	});
	document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
		element.placeholder = translations[language][element.dataset.i18nPlaceholder];
	});
	document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
		element.setAttribute(
			'aria-label',
			translations[language][element.dataset.i18nAriaLabel],
		);
	});
	const page = document.querySelector('main > section')?.id || 'home';
	document.title = translations[language][`page.${page}`];
};

if (languageSelect) {
	languageSelect.value = currentLanguage;
	languageSelect.setAttribute('aria-label', translations[currentLanguage]['nav.language']);
	languageSelect.addEventListener('change', () => {
		const language = languageSelect.value;
		localStorage.setItem('language', language);
		languageSelect.setAttribute('aria-label', translations[language]['nav.language']);
		translatePage(language);
	});
}
translatePage(currentLanguage);

const hamburger = document.getElementById('hamburger');
const navLinks = document.getElementById('navLinks');

hamburger.addEventListener('click', () => {
	hamburger.classList.toggle('active');
	navLinks.classList.toggle('open');
});

navLinks.querySelectorAll('a').forEach((link) => {
	link.addEventListener('click', () => {
		hamburger.classList.remove('active');
		navLinks.classList.remove('open');
	});
});

const themeToggle = document.getElementById('themeToggle');

const savedTheme = localStorage.getItem('theme') || 'dark';
document.documentElement.setAttribute('data-theme', savedTheme);

themeToggle.addEventListener('click', () => {
	const current = document.documentElement.getAttribute('data-theme');
	const next = current === 'dark' ? 'light' : 'dark';
	document.documentElement.setAttribute('data-theme', next);
	localStorage.setItem('theme', next);
});

// ===== Kontaktformular =====
const contactForm = document.getElementById('contactForm');
const formStatus = document.getElementById('formStatus');

const setError = (id, msg) => {
	document.getElementById(id + 'Error').textContent = msg;
};

const isValidEmail = (email) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);

contactForm?.addEventListener('submit', (e) => {
	e.preventDefault();

	const name = document.getElementById('name');
	const email = document.getElementById('email');
	const message = document.getElementById('message');
	let valid = true;

	setError('name', '');
	setError('email', '');
	setError('message', '');
	formStatus.textContent = '';
	formStatus.classList.remove('success');

	if (name.value.trim() === '') {
		setError('name', translations[currentLanguage]['form.nameRequired']);
		valid = false;
	}
	if (!isValidEmail(email.value.trim())) {
		setError('email', translations[currentLanguage]['form.emailInvalid']);
		valid = false;
	}
	if (message.value.trim() === '') {
		setError('message', translations[currentLanguage]['form.messageRequired']);
		valid = false;
	}

	if (valid) {
		const recipient = 'reshad.mandozai@swisscom.com';
		const subject = `${translations[currentLanguage]['form.subject']} ${name.value.trim()}`;
		const body = `Name: ${name.value.trim()}\nE-Mail: ${email.value.trim()}\n\n${message.value.trim()}`;
		const mailtoLink = `mailto:${recipient}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;

		window.location.href = mailtoLink;

		formStatus.textContent = translations[currentLanguage]['form.mailClient'];
		formStatus.classList.add('success');
		contactForm.reset();
	}
});

