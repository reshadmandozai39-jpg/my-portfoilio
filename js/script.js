// Eigenes Dropdown im Theme-Design; das native Select bleibt als Datenquelle versteckt.
const languageNames = { it: 'Italiano', en: 'English', de: 'Deutsch', fr: 'Français' };

if (languageSelect) {
	const dropdown = document.createElement('div');
	dropdown.className = 'lang-dropdown';

	const trigger = document.createElement('button');
	trigger.type = 'button';
	trigger.className = 'lang-trigger';
	trigger.setAttribute('aria-haspopup', 'listbox');
	trigger.setAttribute('aria-expanded', 'false');

	const menu = document.createElement('ul');
	menu.className = 'lang-menu';
	menu.setAttribute('role', 'listbox');
	menu.hidden = true;

	const items = [...languageSelect.options].map((option) => {
		const item = document.createElement('li');
		item.setAttribute('role', 'option');
		item.tabIndex = -1;
		item.dataset.value = option.value;

		const name = document.createElement('span');
		name.textContent = languageNames[option.value] || option.textContent;
		const code = document.createElement('span');
		code.className = 'lang-code';
		code.textContent = option.textContent;

		item.append(name, code);
		menu.append(item);
		return item;
	});

	const isOpen = () => !menu.hidden;

	const syncSelection = () => {
		items.forEach((item) => {
			item.setAttribute('aria-selected', String(item.dataset.value === languageSelect.value));
		});
		trigger.textContent = languageSelect.options[languageSelect.selectedIndex]?.textContent ?? '';
		trigger.setAttribute('aria-label', languageSelect.getAttribute('aria-label'));
	};

	const openMenu = () => {
		menu.hidden = false;
		trigger.setAttribute('aria-expanded', 'true');
		items.find((item) => item.getAttribute('aria-selected') === 'true')?.focus();
	};

	const closeMenu = (returnFocus = false) => {
		menu.hidden = true;
		trigger.setAttribute('aria-expanded', 'false');
		if (returnFocus) trigger.focus();
	};

	const chooseLanguage = (value) => {
		closeMenu(true);
		if (value === languageSelect.value) return;
		languageSelect.value = value;
		languageSelect.dispatchEvent(new Event('change'));
		syncSelection();
	};

	languageSelect.before(dropdown);
	dropdown.append(trigger, menu, languageSelect);
	languageSelect.hidden = true;
	syncSelection();

	trigger.addEventListener('click', () => (isOpen() ? closeMenu() : openMenu()));

	trigger.addEventListener('keydown', (e) => {
		if (e.key === 'ArrowDown' || e.key === 'ArrowUp') {
			e.preventDefault();
			openMenu();
		}
	});

	menu.addEventListener('click', (e) => {
		const item = e.target.closest('li[role="option"]');
		if (item) chooseLanguage(item.dataset.value);
	});

	menu.addEventListener('keydown', (e) => {
		const index = items.indexOf(document.activeElement);
		if (e.key === 'Escape') {
			e.preventDefault();
			closeMenu(true);
		} else if (e.key === 'ArrowDown' || e.key === 'ArrowUp') {
			e.preventDefault();
			const step = e.key === 'ArrowDown' ? 1 : -1;
			items[(index + step + items.length) % items.length].focus();
		} else if (e.key === 'Enter' || e.key === ' ') {
			e.preventDefault();
			if (index !== -1) chooseLanguage(items[index].dataset.value);
		} else if (e.key === 'Tab') {
			closeMenu();
		}
	});

	document.addEventListener('click', (e) => {
		if (isOpen() && !dropdown.contains(e.target)) closeMenu();
	});
}
